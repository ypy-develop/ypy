package gates

// The sheets of the visual matrix (test/fixtures/css, see its README) are third
// party files kept in the repository. Each is listed here with the license file
// that goes with it and its provenance, so the licenses gate reads the license,
// checks that it is MIT and that the file is the one recorded.
func init() {
	for _, f := range []struct{ dir, file, pkg, version, source, sha256 string }{
		{"bootstrap", "bootstrap.min.css", "bootstrap", "5.3.9", "npm: bootstrap@5.3.9 dist/css/bootstrap.min.css",
			"9caac977a0af0c2229abd397eee3345899c4020da2a1a0b711c1cc543fe3719d"},
		{"bulma", "bulma.min.css", "bulma", "1.0.4", "npm: bulma@1.0.4 css/bulma.min.css",
			"67fa26df1ca9e95d8f2adc7c04fa1b15fa3d24257470ebc10cc68b9aab914bee"},
		{"pico", "pico.min.css", "@picocss/pico", "2.1.1", "npm: @picocss/pico@2.1.1 css/pico.min.css",
			"fbc9a63fc9fc9f72d12fd7fc9806e11fa9f77ae4f9cad146b27003a1119ba3db"},
		{"tailwind", "tailwind.css", "tailwindcss", "4.3.5", "generated by the Tailwind CSS v4.3.5 standalone CLI (test/fixtures/css/README.md)",
			"5a448295ea007db4212d1bff5652e9eb4baf1e576d3cd6500f79403289d2ea15"},
	} {
		base := "test/fixtures/css/" + f.dir + "/"
		vendored = append(vendored, struct {
			file, license, want  string
			pkg, version, source string
			sha256, patches      string
		}{base + f.file, base + "LICENSE", "MIT", f.pkg, f.version, f.source, f.sha256, ""})
	}
}
